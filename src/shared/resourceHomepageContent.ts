import MarkdownIt from 'markdown-it'
import { sanitizeRichHtml } from '@/utils/sanitizeHtml'

/**
 * 「资源主页编辑」页的纯文本口径：发布说明的富文本归一、自动简介的生成与识别。
 *
 * 三段都是「进什么出什么」的字符串处理，抽到 shared 是为了让保存链路的用例
 * 不必挂载页面也能断言（保存时提交的 `release_note` 与回显时算出来的内容必须同源）。
 */

const markdownRenderer = new MarkdownIt({
  html: false,
  linkify: true,
  breaks: true,
})
markdownRenderer.enable(['table'])

/**
 * 把发布说明归一成编辑器要显示的富文本：已是 HTML 就只做净化，纯文本按 Markdown 渲染后净化。
 *
 * 加载已保存的内容与保存时都走它，保证「看到的就是存下的」。
 */
export function formatEditorContent(value: string): string {
  const trimmed = value.trim()
  if (!trimmed) {
    return ''
  }

  if (/<\/?[a-z][\s\S]*>/i.test(trimmed)) {
    // 加载已保存的 HTML 内容，使用 sanitizeRichHtml 保持与保存时一致
    return sanitizeRichHtml(trimmed)
  }

  return sanitizeRichHtml(markdownRenderer.render(trimmed))
}

export interface ResourceSummaryInput {
  /** 接口资源不选标签归类、不属于任何根节点 / 二级节点。 */
  isApiKind: boolean
  entryLabel: string
  platformLabel: string
  tagCount: number
}

/** 自动简介（开发者没自己动过简介时才跟着归类勾选变）。 */
export function buildResourceSummary(input: ResourceSummaryInput): string {
  // 接口资源不选标签归类、不属于任何根节点 / 二级节点，简介里只交代「接口资源 · 原创」
  if (input.isApiKind) {
    return '接口资源，原创。'
  }

  return `${input.entryLabel} · ${input.platformLabel}资源，已选择 ${input.tagCount} 个标签。`
}

/**
 * 判断已保存的简介是不是当初自动生成的那句。
 *
 * 是的话，改归类时继续自动跟着变；开发者自己写过简介就不再动它。
 */
export function hasAutoGeneratedDescription(description: string): boolean {
  return /^.+?\s*[·・-]\s*.+资源，已选择 \d+ 个标签。$/.test(description.trim())
}
