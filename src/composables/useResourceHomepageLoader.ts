import { onMounted, watch } from 'vue'
import { TMessage } from 'ui_73info'
import { HttpError } from '@/api/http'
import { getMcResource } from '@/api/mcResources'
import { buildUnifiedAuthUrl } from '@/config/runtime'
import { useAuthStore } from '@/stores/auth'
import type { useResourceHomepageResource } from '@/composables/useResourceHomepageResource'
import type { useResourceHomepageForm } from '@/composables/useResourceHomepageForm'
import type { useResourceTagCatalog } from '@/composables/useResourceTagCatalog'
import type { useResourceApiChannel } from '@/composables/useResourceApiChannel'

/**
 * 本页的加载时序（顺序本身就是业务）：
 *
 * 1. 资源详情先到手，表单才有内容；
 * 2. 标签树到手后再回显勾选——反过来会让「当前二级节点」与勾选落在不同分区上；
 * 3. 归属团队与「团队项目」选项都靠 listMyTeams 的结果，漏掉这一次调用时
 *    teamOptions 恒为空、页面上却看不出是没加载；
 * 4. 同一路由内只改资源 ID 时组件不会重新挂载，得手动复位上一个资源的状态再重载。
 */
export function useResourceHomepageLoader(options: {
  auth: ReturnType<typeof useAuthStore>
  route: ReturnType<typeof useResourceHomepageResource>['route']
  router: ReturnType<typeof useResourceHomepageResource>['router']
  resource: ReturnType<typeof useResourceHomepageResource>['resource']
  loading: ReturnType<typeof useResourceHomepageResource>['loading']
  loadGeneration: ReturnType<typeof useResourceHomepageResource>['loadGeneration']
  formState: ReturnType<typeof useResourceHomepageForm>
  tagCatalog: ReturnType<typeof useResourceTagCatalog>
  channel: ReturnType<typeof useResourceApiChannel>
  loadMyTeams: () => Promise<void>
}) {
  const { auth, route, router, resource, loading, loadGeneration } = options
  const { formState, tagCatalog, channel } = options

  /** 切换到另一个资源前，清掉只属于上一个资源的本地状态（封面文件、渠道配置、标签勾选等）。 */
  function resetResourceScopedState() {
    resource.value = null
    tagCatalog.resetTagSelections()
    formState.resetCoverState()
    channel.resetChannelState()
  }

  async function loadResource(): Promise<boolean> {
    const generation = ++loadGeneration.value
    const resourceId = Number(route.params.resourceId)
    if (!Number.isInteger(resourceId) || resourceId <= 0) {
      TMessage.warning('资源编号无效')
      router.replace({ name: 'dev-resource-list' })
      return false
    }

    if (!auth.token) {
      TMessage.error('登录状态已失效，请重新登录')
      router.replace(buildUnifiedAuthUrl('login', route.fullPath))
      return false
    }

    loading.value = true
    try {
      const payload = await getMcResource(auth.token, resourceId)
      // 快速切换资源时，旧请求的响应直接丢弃
      if (generation !== loadGeneration.value) return false
      resource.value = payload
      formState.applyResourceToForm(payload)

      // 接口资源才去读渠道配置（回调地址 / 掩码 / 允许来源）；普通资源不打扰后端
      if (formState.isApiKind.value) {
        await channel.loadApiChannel(payload.id, generation)
      }
      return generation === loadGeneration.value
    } catch (error) {
      // 旧请求的失败不该弹给已经切到新资源的页面
      if (generation !== loadGeneration.value) return false
      // 404 同时覆盖「资源不存在」与「私有/待审资源无权查看」，按后端原文弹「not found」对用户没意义
      const message =
        error instanceof HttpError && error.status === 404
          ? '资源不存在或无权访问'
          : error instanceof Error
            ? error.message
            : '加载资源详情失败'
      TMessage.error(message)
      router.replace({ name: 'dev-resource-list' })
      return false
    } finally {
      if (generation === loadGeneration.value) loading.value = false
    }
  }

  onMounted(async () => {
    auth.hydrate()
    await loadResource()
    // 标签树到手后（loadTagTree 里按资源实际归类重新定位），再回显标签勾选：
    // 顺序反了会让「当前二级节点」与勾选落在不同分区上。
    await tagCatalog.loadTagTree()
    // 归属团队下拉与「团队项目」选项都靠 listMyTeams 的结果：
    // 漏掉这一次调用时 teamOptions 恒为空、「团队项目」恒为禁用，页面上却看不出是没加载。
    await options.loadMyTeams()
    tagCatalog.applyResourceTagSelections()
    formState.syncAutoGeneratedDescription()
  })

  // 同一路由内只改资源 ID 时组件不会重新挂载：手动复位只属于上一个资源的状态并重载
  watch(
    () => route.params.resourceId,
    async (next, previous) => {
      if (next === undefined || next === previous) return
      resetResourceScopedState()
      if (!(await loadResource())) return
      await tagCatalog.loadTagTree()
      tagCatalog.applyResourceTagSelections()
      formState.syncAutoGeneratedDescription()
    },
  )

  return { loadResource, resetResourceScopedState }
}
