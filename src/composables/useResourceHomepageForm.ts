import { computed, reactive, ref, watch, type Ref } from 'vue'
import { TMessage } from 'ui_73info'
import { apiUrl } from '@/api/http'
import type { McResourcePayload } from '@/api/mcResources'
import type { McTagCatalogEntry } from '@/api/resourceTags'
import { isApiResourceKind } from '@/shared/resourceApi'
import {
  buildResourceSummary,
  formatEditorContent,
  hasAutoGeneratedDescription,
} from '@/shared/resourceHomepageContent'
import {
  createResourceHomepageFormState,
  type ResourceHomepageFormState,
} from '@/shared/resourceHomepageForm'
import { fenToYuanText, promoShareBpsToPercentText } from '@/shared/resourceSale'
import { tagPathSegment } from '@/shared/resourceTagPath'
import { useResourcePricingFields } from '@/composables/useResourcePricingFields'

/** 富文本编辑器暴露给本页的能力（页面内容整块在子组件里，保存链路要能回写内容）。 */
export interface ResourceRichEditorHandle {
  setContent: (html: string, emitUpdate?: boolean) => void
}

/**
 * 资源主页表单本体：字段、图标、发布说明，以及「把服务端资源回填进表单」。
 *
 * 售价与推广分成在 `useResourcePricingFields` 里（互相牵制的规则太多）；
 * 这里只管字段与回填，回填分两种口径：加载（整份覆盖）与保存后（局部纠正 + 清掉待上传文件）。
 */
export function useResourceHomepageForm(options: {
  resource: Ref<McResourcePayload | null>
  boundToRequirement: Ref<boolean>
  /** 当前二级节点（接口资源不在树里，按类别占位显示）。 */
  currentEntry: Ref<McTagCatalogEntry | null>
  currentEntryLabel: Ref<string>
  selectedTagCount: Ref<number>
  editorRef: Ref<ResourceRichEditorHandle | null>
}) {
  const { resource, boundToRequirement, currentEntry, currentEntryLabel, selectedTagCount } =
    options
  const editorRef = options.editorRef

  const form = reactive<ResourceHomepageFormState>(createResourceHomepageFormState())
  const selectedCoverFile = ref<File | null>(null)
  // 图标预览：本地裁剪结果，或已保存封面的完整地址
  const coverPreview = ref('')
  const richEditorContent = ref('')
  const autoGeneratedDescription = ref(false)

  const pricing = useResourcePricingFields(form, { resource, boundToRequirement })

  const isApiKind = computed(() => form.resourceKind === 'api')

  /**
   * 接口资源一律按「原创」归类（不选标签归类、不属于任何根节点 / 二级节点），
   * 表单里不再给「原创 / 转载」这个选择；普通资源仍按开发者选的值提交。
   */
  const effectiveOriginType = computed<'original' | 'repost'>(() =>
    isApiKind.value ? 'original' : form.originType,
  )

  const resourcePlatformLabel = computed(() => {
    // 接口资源不属于任何根节点 / 二级节点，标签树里没有它的平台；用资源类别占位
    if (isApiKind.value) {
      return '接口资源'
    }

    return currentEntry.value?.platform || resource.value?.platform || '未知平台'
  })

  /* ---------- 预览摘要上的读数（标题 / 作者没填时回落到资源本身的值） ---------- */
  const heroTitle = computed(() => form.title.trim() || resource.value?.title || '资源主页')
  const resourceAuthorLabel = computed(
    () => form.author.trim() || resource.value?.author || '开发者',
  )
  /**
   * 预览卡上「二级节点」那一格：优先当前下拉，其次取资源已保存的归类，
   * 都没有才退到平台名（与页面上方读数的口径一致）。
   */
  const previewEntryLabel = computed(
    () =>
      tagPathSegment(1, {
        entryLabel: currentEntry.value?.group_name,
        tagSelections: resource.value?.tag_selections,
      }) || resourcePlatformLabel.value,
  )

  // 组件里的「移除」会回传空串，此时同时清掉已保存的封面地址
  function handleCoverPreviewChange(value: string) {
    coverPreview.value = value
    if (!value) {
      form.cover_url = ''
    }
  }

  /** 发布说明编辑器冒上来的提示（无效链接 / 图片地址之类），口径与全站一致。 */
  function notify(message: string, type: 'info' | 'success' | 'warning' | 'error' = 'info') {
    TMessage[type](message)
  }

  function onDescriptionInput() {
    // 开发者自己动过简介，就不再跟着归类勾选自动改写
    autoGeneratedDescription.value = false
  }

  function syncAutoGeneratedDescription() {
    if (!autoGeneratedDescription.value) return
    form.description = buildResourceSummary({
      isApiKind: isApiKind.value,
      entryLabel: currentEntryLabel.value,
      platformLabel: resourcePlatformLabel.value,
      tagCount: selectedTagCount.value,
    })
  }

  watch([currentEntryLabel, resourcePlatformLabel, selectedTagCount], () =>
    syncAutoGeneratedDescription(),
  )

  function syncEditorContent(value: string) {
    const normalized = formatEditorContent(value)
    richEditorContent.value = normalized
    form.release_note = normalized
    editorRef.value?.setContent(normalized || '<p></p>', false)
  }

  function handleRichEditorUpdate(value: string) {
    richEditorContent.value = value
    form.release_note = value
  }

  /** 加载资源后把服务端字段整份回填进表单。 */
  function applyResourceToForm(payload: McResourcePayload) {
    form.title = payload.title
    form.author = payload.author
    form.description = payload.description
    autoGeneratedDescription.value = hasAutoGeneratedDescription(payload.description)
    form.cover_url = payload.cover_url || ''
    form.docs_url = payload.docs_url || ''
    form.release_note = payload.release_note || ''
    form.ownershipType = payload.ownership_type === 'team' ? 'team' : 'individual'
    form.teamId =
      payload.ownership_type === 'team' && payload.team_id ? String(payload.team_id) : ''
    form.originType = payload.origin_type === 'repost' ? 'repost' : 'original'
    form.originAuthor = payload.origin_author || ''
    form.originUrl = payload.origin_url || ''
    form.originOrg = payload.origin_org || ''
    form.originNote = payload.origin_note || ''
    form.priceYuan = fenToYuanText(payload.buyout_price_fen ?? 0)
    form.pricePoints = String(Math.max(0, Math.trunc(Number(payload.price_points ?? 0))))
    // R029：比例以万分比存，回显换算回百分比数值（1000 → 10；0 → 0）
    form.promoSharePercent = Number(promoShareBpsToPercentText(payload.promo_share_bps) || 0)
    form.copyrightDeclared = Boolean(payload.copyright_declared)
    form.resourceKind = isApiResourceKind(payload.resource_kind) ? 'api' : 'normal'
    coverPreview.value = payload.cover_url ? apiUrl(payload.cover_url) : ''
    syncEditorContent(payload.release_note || '')
  }

  /**
   * 保存成功后按服务端返回值纠正表单（后端可能规整过字段），并清掉待上传的图标文件。
   * 标题与简介不回写：它们就是刚提交上去的值，回写只会把光标里的草稿顶掉。
   */
  function applySavedHomepage(updated: McResourcePayload) {
    form.author = updated.author
    form.cover_url = updated.cover_url || ''
    form.docs_url = updated.docs_url || ''
    form.release_note = updated.release_note || ''
    form.originType = updated.origin_type
    form.originAuthor = updated.origin_author || ''
    form.originUrl = updated.origin_url || ''
    form.originOrg = updated.origin_org || ''
    form.originNote = updated.origin_note || ''
    form.priceYuan = fenToYuanText(updated.buyout_price_fen ?? 0)
    form.pricePoints = String(Math.max(0, Math.trunc(Number(updated.price_points ?? 0))))
    form.promoSharePercent = Number(promoShareBpsToPercentText(updated.promo_share_bps) || 0)
    form.copyrightDeclared = Boolean(updated.copyright_declared)
    selectedCoverFile.value = null
    coverPreview.value = updated.cover_url ? apiUrl(updated.cover_url) : ''
    syncEditorContent(updated.release_note || '')
  }

  /** 换资源前复位只属于上一个资源的那部分表单状态。 */
  function resetCoverState() {
    selectedCoverFile.value = null
    coverPreview.value = ''
  }

  return {
    form,
    isApiKind,
    effectiveOriginType,
    resourcePlatformLabel,
    heroTitle,
    resourceAuthorLabel,
    previewEntryLabel,
    selectedCoverFile,
    coverPreview,
    richEditorContent,
    autoGeneratedDescription,
    handleCoverPreviewChange,
    notify,
    onDescriptionInput,
    handleRichEditorUpdate,
    syncAutoGeneratedDescription,
    syncEditorContent,
    applyResourceToForm,
    applySavedHomepage,
    resetCoverState,
    ...pricing,
  }
}
