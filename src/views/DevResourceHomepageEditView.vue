    if (resource.value) {
      // 资源已在手：按资源自身的归类重新定位（刷新标签后不能把回显丢回首项）。
      // 已经定位到过的保持现状——刷新不该覆盖开发者当前正在改的归类与勾选。
      if (!tagPathResolved.value) {
        tagPathResolved.value = resolveTagPathFromResource()
        if (!tagPathResolved.value) {
          applyDisplayTagPathFallback()
        }
      }
      return
    }

    const firstRoot = processedTree.value.roots[0]
    if (firstRoot && !processedTree.value.roots.some((r) => r.key === currentRootKey.value)) {
      currentRootKey.value = firstRoot.key
      currentEntryKey.value = firstRoot.first_entry_key ?? ''
    }
  } catch (error) {
    const message = error instanceof Error ? error.message : '加载标签失败'
    TMessage.error(message)
  } finally {
    isLoadingTags.value = false
  }
}

/**
 * 根节点下拉改选：二级节点随之落到新根节点的首个二级节点，
 * 避免留下上一棵树里的失效 key（那会让二级节点停在兜底项上，看起来像没跟着切）。
 */
function selectRoot(value: SelectModelValue) {
  const rootKey = typeof value === 'string' ? value : ''
  const root = rootTabs.value.find((item) => item.key === rootKey)
  if (!root) return
  currentRootKey.value = root.key
  currentEntryKey.value = root.first_entry_key ?? ''
  // 开发者自己选的归类，就是本次要提交的归类
  tagPathResolved.value = true
}

/** 二级节点下拉改选：选项由当前根节点决定，这里再确认一次值还在候选里。 */
function selectEntry(value: SelectModelValue) {
  const entryKey = typeof value === 'string' ? value : ''
  if (!entryTabs.value.some((entry) => entry.key === entryKey)) return
  currentEntryKey.value = entryKey
  tagPathResolved.value = true
}

function buildTagSelections(): CreateMcResourceTagSelection[] {
  // 接口资源不选标签归类、不属于任何根节点 / 二级节点：一个标签都不提交
  if (isApiKind.value) {
    return []
  }

  const selections = platformTagGroups.value
    .map((group) => ({
      group_id: group.group_id,
      tag_ids: [...(selectedTagIdsByGroup[group.group_id] ?? [])],
    }))
    .filter((selection) => selection.tag_ids.length > 0)

  // 资源归类没定位到、界面上是回落项且一个标签都没勾时，别把它当成「开发者清空了所有标签」
  // 写回去 —— 原样回传资源已保存的归类（keepSavedTags 的判定见其注释）。
  if (keepSavedTags.value && selections.length === 0) {
    return (resource.value?.tag_selections ?? []).map((selection) => ({
      group_id: selection.group_id,
      tag_ids: [...selection.tag_ids],
    }))
  }

  return selections
}

/**
 * 按资源自身的归类定位「根节点 / 二级节点」（只定位，不改勾选）。
 *
 * 优先级：标签选择的 `group_path` 前两段（美术 / 手绘，就是资源实际归属，最可靠）
 * → 资源的 `platform` 匹配二级节点名（历史资源的平台字段口径）。
 * 两轮都定位不到就不动当前下拉值，返回假——由调用方记住「当前只是回落展示」。
 */
function resolveTagPathFromResource(): boolean {
  for (const selection of resource.value?.tag_selections ?? []) {
    const rootLabel = normalizePlatform(selection.group_path[0])
    const entryLabel = normalizePlatform(selection.group_path[1])
    if (!rootLabel || !entryLabel) continue
    const root = rootTabs.value.find(
      (item) =>
        normalizePlatform(item.label) === rootLabel || normalizePlatform(item.key) === rootLabel,
    )
    // 二级节点的名字在各棵树里既有 `group_name` 也有 `platform`，两个都比一次：
    // 只比 group_name 时，`group_path` 里存的是平台名的资源会定位不到。
    const entry = root?.entries.find(
      (item) =>
        normalizePlatform(item.group_name) === entryLabel ||
        normalizePlatform(item.platform) === entryLabel,
    )
    if (!root || !entry) continue
    currentRootKey.value = root.key
    currentEntryKey.value = entry.key
    return true
  }

  const platform = normalizePlatform(resource.value?.platform)
  if (!platform) {
    return false
  }

  const root = rootTabs.value.find((item) =>
    item.entries.some((entry) => normalizePlatform(entry.platform) === platform),
  )
  const entry = root?.entries.find((item) => normalizePlatform(item.platform) === platform)
  if (!root || !entry) {
    return false
  }

  currentRootKey.value = root.key
  currentEntryKey.value = entry.key
  return true
}

/**
 * 归类定位不到时的展示回落：下拉停在标签树的根节点 / 其首个二级节点上。
 *
 * 只改下拉的展示值，**不改 `tagPathResolved`**——它为假表示界面上这份归类不是资源的，
 * 保存时由 `keepSavedTags` 换回资源原有归类。下拉自身不能空着：
 * 空值会让两个下拉都显示占位符，和旁边「当前：<回落项>」的读数自相矛盾。
 */
function applyDisplayTagPathFallback() {
  if (!rootTabs.value.some((root) => root.key === currentRootKey.value)) {
    currentRootKey.value = rootTabs.value[0]?.key ?? ''
  }
  const entries = currentRoot.value?.entries ?? []
  if (!entries.some((entry) => entry.key === currentEntryKey.value)) {
    currentEntryKey.value = entries[0]?.key ?? ''
  }
}

function applyResourceTagSelections() {
  const selections = resource.value?.tag_selections ?? []
  for (const key of Object.keys(selectedTagIdsByGroup)) {
    delete selectedTagIdsByGroup[Number(key)]
  }
  for (const sel of selections) {
    selectedTagIdsByGroup[sel.group_id] = [...sel.tag_ids]
  }

  tagPathResolved.value = resolveTagPathFromResource()
  if (!tagPathResolved.value) {
    applyDisplayTagPathFallback()
  }
}

/** 切换到另一个资源前，清掉只属于上一个资源的本地状态（封面文件、渠道配置、标签勾选等）。 */
function resetResourceScopedState() {
  resource.value = null
  tagPathResolved.value = false
  selectedCoverFile.value = null
  coverPreview.value = ''
  savedApiChannel.value = null
  revealedSecretPlain.value = ''
  secretPlainDialogVisible.value = false
  channelRetryOnly.value = false
  channelSaveError.value = ''
  form.apiCallbackUrl = ''
  form.apiCallbackSecret = ''
  form.apiAllowedOrigins = ''
  form.apiRepeatPurchasable = false
  for (const key of Object.keys(selectedTagIdsByGroup)) {
    delete selectedTagIdsByGroup[Number(key)]
  }
}

async function loadResource(): Promise<boolean> {
  const generation = ++resourceLoadGeneration
  const resourceId = Number(route.params.resourceId)
  if (!Number.isInteger(resourceId) || resourceId <= 0) {
    TMessage.warning('资源编号无效')
    router.replace({ name: 'dev-resource-list' })
    return false
  }

  if (!auth.token) {
    TMessage.error('登录状态已失效，请重新登录')
    router.replace(buildUnifiedAuthUrl('login', route.fullPath))
    return false
  }

  loading.value = true
  try {
    const payload = await getMcResource(auth.token, resourceId)
    // 快速切换资源时，旧请求的响应直接丢弃
    if (generation !== resourceLoadGeneration) return false
    resource.value = payload
    form.title = payload.title
    form.author = payload.author
    form.description = payload.description
    autoGeneratedDescription.value = hasAutoGeneratedDescription(payload)
    form.cover_url = payload.cover_url || ''
    form.docs_url = payload.docs_url || ''
    form.release_note = payload.release_note || ''
    form.ownershipType = payload.ownership_type === 'team' ? 'team' : 'individual'
    form.teamId =
      payload.ownership_type === 'team' && payload.team_id ? String(payload.team_id) : ''
    form.originType = payload.origin_type === 'repost' ? 'repost' : 'original'
    form.originAuthor = payload.origin_author || ''
    form.originUrl = payload.origin_url || ''
    form.originOrg = payload.origin_org || ''
    form.originNote = payload.origin_note || ''
    form.priceYuan = fenToYuanText(payload.price_fen ?? 0)
    form.pricePoints = String(Math.max(0, Math.trunc(Number(payload.price_points ?? 0))))
    // R029：比例以万分比存，回显换算回百分比数值（1000 → 10；0 → 0）
    form.promoSharePercent = Number(promoShareBpsToPercentText(payload.promo_share_bps) || 0)
    form.copyrightDeclared = Boolean(payload.copyright_declared)
    form.resourceKind = isApiResourceKind(payload.resource_kind) ? 'api' : 'normal'
    coverPreview.value = payload.cover_url ? apiUrl(payload.cover_url) : ''
    syncEditorContent(payload.release_note || '')

    // 接口资源才去读渠道配置（回调地址 / 掩码 / 允许来源）；普通资源不打扰后端
    if (form.resourceKind === 'api') {
      await loadApiChannel(payload.id, generation)
    }
    return generation === resourceLoadGeneration
  } catch (error) {
    // 旧请求的失败不该弹给已经切到新资源的页面
    if (generation !== resourceLoadGeneration) return false
    // 404 同时覆盖「资源不存在」与「私有/待审资源无权查看」，按后端原文弹「not found」对用户没意义
    const message =
      error instanceof HttpError && error.status === 404
        ? '资源不存在或无权访问'
        : error instanceof Error
          ? error.message
          : '加载资源详情失败'
    TMessage.error(message)
    router.replace({ name: 'dev-resource-list' })
    return false
  } finally {
    if (generation === resourceLoadGeneration) loading.value = false
  }
}

async function saveHomepage() {
  if (!auth.token || !resource.value) {
    TMessage.error('登录状态已失效，请重新登录')
    return
  }

  // 锁定态只是前置拦截；后端 PATCH 主页接口仍会以 409 + 中文提示兜底。
  if (isResourceArchiveLocked(resource.value)) {
    TMessage.warning(RESOURCE_ARCHIVE_LOCKED_MESSAGE)
    return
  }

  if (needsApiAgreement.value) {
    TMessage.warning('请先签署《接口使用协议》后再编辑接口资源')
    return
  }

  if (!form.title.trim() || !form.description.trim()) {
    TMessage.warning('请先填写资源标题和资源简介')
    return
  }

  // 接口资源不选标签归类，标签相关的必填项对它不成立；
  // 归类没能在标签树里定位到的资源也跳过：界面上那份是回落展示，
  // 本次提交的是资源原有归类（见 keepSavedTags 与 buildTagSelections），不该被这里的必填挡住。
  if (
    !isApiKind.value &&
    !keepSavedTags.value &&
    (platformTagGroups.value.length === 0 || selectedTagCount.value === 0)
  ) {
    TMessage.warning('请至少选择一个标签')
    return
  }

  if (form.ownershipType === 'team' && !form.teamId) {
    TMessage.warning('请选择所属团队')
    return
  }

  if (effectiveOriginType.value === 'repost' && !form.originUrl.trim()) {
    TMessage.warning('转载资源必须填写原始出处链接')
    return
  }

  const priceParsed = parseYuanPriceInput(form.priceYuan)
  if (!priceParsed.ok) {
    TMessage.warning(priceParsed.message)
    return
  }
  const pointsParsed = parsePointsPriceInput(form.pricePoints)
  if (!pointsParsed.ok) {
    TMessage.warning(pointsParsed.message)
    return
  }
  if (priceParsed.fen > 0 && pointsParsed.points > 0) {
    TMessage.warning('现金售价与积分售价不能同时大于 0')
    return
  }
  // R028：接口资源只走现金价（积分购是平台内入口，指定地址售卖没有它）
  if (isApiKind.value) {
    if (pointsParsed.points > 0) {
      TMessage.warning('接口资源只能设置现金售价，不能设置积分售价')
      return
    }
    // 已上架（审核中 / 公开展示）的接口资源必须留现金售价，否则开放接口卖不出去
    if (
      priceParsed.fen <= 0 &&
      (resource.value.visibility === 'review' || resource.value.visibility === 'published')
    ) {
      TMessage.warning('接口资源必须填写现金售价（元）')
      return
    }
  }
  // R029：推广分成比例先在前端拦一道（0～50，留空 = 关闭）；清空保存 = 把比例改回 0
  const promoParsed = parsedPromoShare.value
  if (!promoParsed.ok) {
    TMessage.warning(promoParsed.message)
    return
  }
  if (pointsParsed.points > 0 && pointsLockedBySavedCash.value) {
    TMessage.warning('设过现金售价的资源不可改为积分售价')
    return
  }
  if (boundToRequirement.value && (priceParsed.fen > 0 || pointsParsed.points > 0)) {
    TMessage.warning('已绑定定制交付的资源不能设为付费售卖')
    return
  }
  if (
    (priceParsed.fen > 0 || pointsParsed.points > 0) &&
    !form.copyrightDeclared &&
    (resource.value.visibility === 'review' || resource.value.visibility === 'published')
  ) {
    TMessage.warning('付费资源须勾选版权声明（拥有或已获合法授权）')
    return
  }

  if (!validateApiChannel()) {
    return
  }

  saving.value = true
  try {
    // 资源主页上一轮已保存、只有渠道配置没成功：这一次只重发渠道配置这一半
    if (channelRetryOnly.value && isApiKind.value && resource.value) {
      if (await saveApiChannelOnly(resource.value.id)) {
        TMessage.success('接口资源渠道配置已保存')
      }
      return
    }

    // 后端把 JSON null 视为「未传」，清空封面必须传空串（空串会被规整为 NULL）
    let nextCoverUrl: string | null = form.cover_url.trim()

    if (selectedCoverFile.value) {
      const coverUpdated = await uploadMcResourceCover(
        auth.token,
        resource.value.id,
        selectedCoverFile.value,
      )
      nextCoverUrl = coverUpdated.cover_url
      form.cover_url = coverUpdated.cover_url || ''
    }

    const updated = await updateMcResourceHomepage(auth.token, resource.value.id, {
      title: form.title.trim(),
      author: form.author.trim(),
      description: form.description.trim(),
      tag_selections: buildTagSelections(),
      // cover_url / release_note 传空串表示清空，传 null 后端会当成没改
      cover_url: nextCoverUrl,
      docs_url: form.docs_url.trim() || null,
      // 保存时用 sanitizeRichHtml 将 language-md 代码块渲染为富文本
      release_note: sanitizeRichHtml(form.release_note.trim()),
      ownership_type: form.ownershipType,
      team_id: form.ownershipType === 'team' && form.teamId ? Number(form.teamId) : null,
      origin_type: effectiveOriginType.value,
      origin_author: form.originAuthor.trim() || null,
      origin_url: form.originUrl.trim() || null,
      origin_org: form.originOrg.trim() || null,
      origin_note: form.originNote.trim() || null,
      price_fen: priceParsed.fen,
      price_points: isApiKind.value ? 0 : pointsParsed.points,
      copyright_declared: form.copyrightDeclared,
      // R029：比例整体提交，0 也显式下发——清空回 0 这种操作不能靠省略字段变成静默失效
      promo_share_bps: promoParsed.bps,
    })

    resource.value = updated
    form.author = updated.author
    form.cover_url = updated.cover_url || ''
    form.docs_url = updated.docs_url || ''
    form.release_note = updated.release_note || ''
    form.originType = updated.origin_type
    form.originAuthor = updated.origin_author || ''
    form.originUrl = updated.origin_url || ''
    form.originOrg = updated.origin_org || ''
    form.originNote = updated.origin_note || ''
    form.priceYuan = fenToYuanText(updated.price_fen ?? 0)
    form.pricePoints = String(Math.max(0, Math.trunc(Number(updated.price_points ?? 0))))
    form.promoSharePercent = Number(promoShareBpsToPercentText(updated.promo_share_bps) || 0)
    form.copyrightDeclared = Boolean(updated.copyright_declared)
    selectedCoverFile.value = null
    coverPreview.value = updated.cover_url ? apiUrl(updated.cover_url) : ''
    syncEditorContent(updated.release_note || '')

    // R028：资源本身存好了，再 PUT 渠道配置；失败要明确报错并留在表单上（重试只重发这一半）
    if (isApiKind.value && !(await saveApiChannelOnly(updated.id))) {
      return
    }

    TMessage.success(
      updated.visibility === 'review'
        ? '资源主页已保存，已提交重新审核，审核期间前台暂不展示'
        : '资源主页已更新',
    )

    if (revealedSecretPlain.value) {
      TMessage.warning('回调密钥已生成，且只显示这一次，请立即复制保存')
    }
  } catch (error) {
    const message = error instanceof Error ? error.message : '更新资源主页失败'
    TMessage.error(message)
  } finally {
    saving.value = false
  }
}

function goBack() {
  if (window.history.state?.back) {
    router.back()
    return
  }
  router.push({ name: 'dev-resource-list' })
}

function selectedTagPathSegment(index: number): string {
  if (index === 0 && currentRoot.value) {
    return currentRoot.value.label
  }

  if (index === 1 && currentEntry.value) {
    return currentEntry.value.group_name
  }

  return firstTagPathSegment(index)
}

function firstTagPathSegment(index: number): string {
  return (
    resource.value?.tag_selections.find((item) => item.group_path[index])?.group_path[index] ?? ''
  )
}

function userClientResourceUrl(target: McResourcePayload): string {
  const rootSlug = getTagRouteSlug(firstTagPathSegment(0) || 'resources')
  const entrySlug = getTagRouteSlug(firstTagPathSegment(1) || target.platform || 'detail')
  // 独立详情页已废弃：站内分享地址统一指到列表页的页内详情态（`?resource=`）
  const routeLocation = router.resolve(
    resourceDetailLocation({
      resourceId: target.id,
      rootSlug,
      entrySlug,
      sale: resourceListingSaleOf(target.price_fen, target.price_points),
    }),
  )

  const configuredBase = (import.meta.env.VITE_USER_CLIENT_BASE_URL as string | undefined)?.trim()
  const baseUrl = configuredBase ? configuredBase.replace(/\/$/, '') + '/' : window.location.href
  return new URL(routeLocation.href, baseUrl).toString()
}

