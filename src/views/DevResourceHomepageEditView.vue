  // 顺序反了会让「当前二级节点」与勾选落在不同分区上。
  await loadTagTree()
  // 归属团队下拉与「团队项目」选项都靠 listMyTeams 的结果：
  // 漏掉这一次调用时 teamOptions 恒为空、「团队项目」恒为禁用，页面上却看不出是没加载。
  await loadMyTeams()
  applyResourceTagSelections()
  syncAutoGeneratedDescription()
})

// 同一路由内只改资源 ID 时组件不会重新挂载：手动复位只属于上一个资源的状态并重载
